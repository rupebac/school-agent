function interpolate(template: string, params?: Record<string, string | number>): string {
  if (!params) return template;
  let out = template;
  for (const [k, v] of Object.entries(params)) {
    out = out.replaceAll(`{${k}}`, String(v));
  }
  return out;
}

@Injectable({ providedIn: 'root' })
export class I18n {
  readonly lang = signal<Lang>('en');
  private readonly overlay = signal<Record<string, string> | null>(null);

  locale(): string {
    return this.lang() === 'es' && this.overlay() ? 'es' : 'en-GB';
  }

  /** Tests can inject a pack without a dynamic import. */
  applyPack(lang: Lang, pack: Record<string, string> | null): void {
    this.lang.set(lang);
    this.overlay.set(lang === 'en' ? null : pack);
    if (typeof document !== 'undefined') document.documentElement.lang = lang;
  }

  setLang(raw: string | null | undefined): Lang {
    const lang: Lang = raw?.trim().toLowerCase().startsWith('es') ? 'es' : 'en';
    this.lang.set(lang);
    if (typeof document !== 'undefined') document.documentElement.lang = lang;
    if (lang === 'es' && !this.overlay()) {
      void import('./i18n.es').then((m) => {
        if (this.lang() === 'es') this.overlay.set(m.ES);
      });
    }
    if (lang === 'en') this.overlay.set(null);
    return lang;
  }

  t(key: string, params?: Record<string, string | number>): string {
    const extra = this.lang() === 'es' ? this.overlay() : null;
    return interpolate(extra?.[key] ?? EN[key] ?? key, params);
  }

  weekdays(): string[] {
    return [0, 1, 2, 3, 4, 5, 6].map((i) => this.t(`cal.wd.${i}`));
  }
}

@Pipe({ name: 't', pure: false })
export class TranslatePipe implements PipeTransform {
  private readonly i18n = inject(I18n);
  transform(key: string, params?: Record<string, string | number>): string {
    this.i18n.lang();
    return this.i18n.t(key, params);
  }
}

@Pipe({ name: 'ldate', pure: false })
export class LocDatePipe implements PipeTransform {
  private readonly i18n = inject(I18n);
  transform(value: Date | string | number | null | undefined, format: string): string {
    this.i18n.lang();
    if (value == null || value === '') return '';
    return new DatePipe(this.i18n.locale()).transform(value, format, undefined, this.i18n.locale()) ?? '';
  }
}
